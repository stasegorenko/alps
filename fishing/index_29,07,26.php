<script>
    (function() {
        'use strict';

        const track = document.getElementById('videoTrack');
        if (!track) return;

        const slides = track.querySelectorAll('.video-carousel-slide');
        const total = slides.length;

        if (total <= 1) return;

        let current = 0;
        let isAnimating = false;

        const prevBtn = document.getElementById('videoPrevBtn');
        const nextBtn = document.getElementById('videoNextBtn');
        const dots = document.querySelectorAll('.video-dot');
        const wrapper = document.querySelector('.video-carousel-wrapper');
        function updateActiveSlide() {
            slides.forEach((slide, index) => {
                slide.classList.toggle('active-slide', index === current);
            });
        }

        function pauseAllVideos() {
            slides.forEach(function(slide) {
                const iframe = slide.querySelector('iframe');
                if (iframe) {
                    try {
                        if (iframe.contentWindow) {
                            iframe.contentWindow.postMessage('{"event":"command","func":"pauseVideo","args":""}', '*');
                        }
                    } catch(e) {}
                }
            });
        }

        function goToSlide(index) {
            if (isAnimating) return;
            if (index < 0) index = total - 1;
            if (index >= total) index = 0;
            if (index === current) return;

            isAnimating = true;

            pauseAllVideos();

            current = index;
            let windowWidth = window.innerWidth;
            let offset = 0;
            
            if (windowWidth >= 992) {
                if (current === 0) {
                    offset = 0;
                } else if (current === total - 1) {
                    offset = -(total - 3) * (100 / 3);
                } else {
                    offset = -(current - 1) * (100 / 3);
                }
            } else if (windowWidth >= 768) {
                if (current === 0) {
                    offset = 0;
                } else if (current === total - 1) {
                    offset = -(total - 2) * 50;
                } else {
                    offset = -(current - 0.5) * 50;
                }
            } else {
                offset = -(current * 100);
            }
            
            track.style.transform = 'translateX(' + offset + '%)';

            updateActiveSlide();

            dots.forEach((dot, i) => {
                dot.classList.toggle('active', i === current);
            });

            setTimeout(() => {
                isAnimating = false;
            }, 600);
        }

        let resizeTimer;
        window.addEventListener('resize', function() {
            clearTimeout(resizeTimer);
            resizeTimer = setTimeout(function() {
                goToSlide(current);
            }, 250);
        });

        updateActiveSlide();

        if (prevBtn && nextBtn) {
            prevBtn.addEventListener('click', function(e) {
                e.preventDefault();
                goToSlide(current - 1);
            });

            nextBtn.addEventListener('click', function(e) {
                e.preventDefault();
                goToSlide(current + 1);
            });
        }

        dots.forEach(function(dot, index) {
            dot.addEventListener('click', function() {
                goToSlide(index);
            });
        });

        document.addEventListener('keydown', function(e) {
            if (e.key === 'ArrowLeft') {
                e.preventDefault();
                goToSlide(current - 1);
            } else if (e.key === 'ArrowRight') {
                e.preventDefault();
                goToSlide(current + 1);
            }
        });

        let autoplayTimer = setInterval(function() {
            goToSlide(current + 1);
        }, 6000);

        if (wrapper) {
            wrapper.addEventListener('mouseenter', function() {
                clearInterval(autoplayTimer);
            });

            wrapper.addEventListener('mouseleave', function() {
                clearInterval(autoplayTimer);
                autoplayTimer = setInterval(function() {
                    goToSlide(current + 1);
                }, 6000);
            });
        }

